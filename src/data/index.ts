export function findMatchingRegion(query: string): string | null {
  const q = query.toLowerCase().trim();
  for (const region of Object.keys(italianRegions)) {
    if (region.includes(q) || q.includes(region)) {
      return region;
    }
  }
  return null;
}

export function getCitiesForQuery(query: string): string[] {
  const region = findMatchingRegion(query);
  if (region) {
    return italianRegions[region].cities;
  }
  return [];
}

export function getProvincesForQuery(query: string): string[] {
  const region = findMatchingRegion(query);
  if (region) {
    return italianRegions[region].provinces;
  }
  return [];
}

